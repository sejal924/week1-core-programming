//converting the distance from kilometer to miles
import java.util.*;

//creating the KilometerToMiles class
public class KilometerToMiles
{
     public static void main(String [] args)
     { 
	      //creating the variable kilometer , mile
          double kilometer = 10.8;
		  // converting the kilometer to mile
          double mile = 10.8/1.6;
		  //printing the distance in miles
          System.out.print("The distance" + kilometer + "km in miles is " + mile);
     }
}